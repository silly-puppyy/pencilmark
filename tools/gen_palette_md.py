"""Write docs/PALETTE.md from docs/palette.json: every size and colour of the default drawing, with a light and a dark
preview drawn by tools/render_svg.py (the docs build's swatches). Plain Markdown; the site puts a colour chip beside
each hex colour (website/src/plugins/inline-json.mjs).
  python tools/gen_palette_md.py"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAL = json.loads((ROOT / "docs" / "palette.json").read_text(encoding="utf-8"))
PREVIEWS = ["example-mini-thermo-kropki", "example-killer-4x4", "example-jigsaw-6x6"]
SIZES = {  # size -> what it measures
    "thin": "grid lines",
    "box": "box borders",
    "frame": "the board's outer frame",
    "box_dark": "box borders in the dark theme (light lines on dark read thinner)",
    "digit": "digit height",
    "given_w": "font weight of givens",
    "placed_w": "font weight of placed digits (solver output; not drawn by render_svg)",
    "halo_light": "outline in the board colour around each digit, so it reads over lines (light theme)",
    "halo_dark": "the same outline, dark theme",
    "line": "default width of line rules (whisper, renban, ...)",
    "thermo": "thermometer width",
    "bulb": "thermometer bulb radius",
}
ROLES = {  # theme colour -> where it is used
    "page": "around the board",
    "board": "the board",
    "ink": "box borders and the frame",
    "thin": "grid lines",
    "given": "given digits, cage outlines, clue circle rims",
    "placed": "placed digits (solver output; not drawn by render_svg)",
    "cand": "candidates, row / column labels, equal-sum segment outlines",
    "shade": "window / extra region shading",
    "diag": "diagonals",
    "clue_bg": "behind small clues (circles, corner sum boxes)",
    "odd": "odd-cell circles",
    "even": "even-cell squares",
    "low": "diamonds in cells marked low",
    "high": "diamonds in cells marked high",
    "text": "running text beside a board (not drawn by render_svg)",
}


def page():
    light, dark = PAL["themes"]["light"], PAL["themes"]["dark"]
    L = [
        "---",
        "title: Palette",
        "description: Every size and colour of pencilmark's default drawing, generated from docs/palette.json.",
        "---",
        "",
        "# Palette",
        "",
        "Every size and colour of the default drawing, from [`docs/palette.json`](palette.json) (format "
        f"`{PAL['format']}`, version {PAL['format_version']}); [Drawing and style](STYLE.md) says how each rule uses "
        "them. Generated by `tools/gen_palette_md.py`. None of it is part of a puzzle format: a renderer may draw "
        "differently.",
        "",
        "## Preview",
        "",
        "The example puzzles drawn by `tools/render_svg.py`, light theme above, dark below.",
        "",
        " ".join(f"![{n.removeprefix('example-')}](/img/swatches/{n}.svg)" for n in PREVIEWS),
        "",
        " ".join(f"![{n.removeprefix('example-')}, dark](/img/swatches/{n}-dark.svg)" for n in PREVIEWS),
        "",
        "## Themes",
        "",
        "| Colour | Light | Dark | Used for |",
        "|---|---|---|---|",
    ]
    L += [f"| `{k}` | `{light[k]}` | `{dark.get(k, '')}` | {ROLES.get(k, '')} |" for k in light]
    L += ["", "## Line colours", "", "The community defaults, as measured on 6,217 published puzzles; the same in "
          "both themes.", "", "| Line | Colour |", "|---|---|"]  # fmt: skip
    L += [f"| `{k}` | `{v}` |" for k, v in PAL["lines"].items()]
    L += ["", "## Region shading", "", "`region` `colour` rules take these in rule order, repeating.", ""]
    L += [" ".join(f"`{c}`" for c in PAL["region_palette"]), ""]
    L += ["## Bands", "", "A colour per band, for software that shows a card (render_svg draws boards only).", "",
          "| Band | Colour |", "|---|---|"]  # fmt: skip
    L += [f"| {k} | `{v}` |" for k, v in PAL["bands"].items()]
    L += ["", "## Sizes", "", "In cell units (1 = a cell's side); font weights as CSS weights.", "",
          "| Size | Value | Measures |", "|---|---|---|"]  # fmt: skip
    L += [f"| `{k}` | {v} | {SIZES.get(k, '')} |" for k, v in PAL["sizes"].items()]
    return "\n".join(L) + "\n"


def main():
    missing = (set(PAL["sizes"]) - set(SIZES)) | (set(PAL["themes"]["light"]) - set(ROLES))
    if missing:
        raise SystemExit(f"palette entries without a description in gen_palette_md.py: {sorted(missing)}")
    (ROOT / "docs" / "PALETTE.md").write_text(page(), encoding="utf-8")


if __name__ == "__main__":
    main()
