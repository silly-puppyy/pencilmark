SETS = {
    "route": "Engine parameters (route)",
    "price": "Difficulty prices (price)",
    "score": "Card score (score)",
    "time": "Time model (time)",
}


def fmt(v):
    if isinstance(v, float):
        return f"{v:.4g}"
    if isinstance(v, list):
        return f"list of {len(v)}" if len(v) > 4 else ", ".join(fmt(x) for x in v)
    if isinstance(v, str):
        return v if len(v) < 60 else v[:57] + "..."
    return str(v)


def source(name):
    best = max((p for p in PROVENANCE if name.startswith(p)), key=len, default=None)
    return PROVENANCE.get(best, "")


def page():
    names = GM.GraderModel.load().names()
    L = [
        "---",
        "title: Grader parameters",
        "description: Every fitted parameter of the grader by name, with its value and where it comes from.",
        "---",
        "",
        "# Grader parameters",
        "",
        "Every number the grader uses, by the name `grader_model` gives it (`names()`, `with_overrides()`, `use()`; see",
        "`src/pencilmark/grader_model.py`). The difficulty prices share every value with the engine parameters except two",
        "weight vectors, so only those are listed under them. This page is generated by `tools/gen_parameters_md.py`;",
        "changing a shipped value is a deliberate commit with a golden rewrite.",
        "",
    ]
    for k, title in SETS.items():
        rows = [(n, v) for n, v in names.items() if n.startswith(k + ".")]
        if k == "price":  # only what differs from route
            rows = [(n, v) for n, v in rows if names.get("route." + n[len("price.") :]) != v]
        L += [f"## {title}", "", "| Name | Value | Source |", "|---|---|---|"]
        last = None
        for n, v in rows:
            src = source(n)
            L.append(f"| `{n}` | {fmt(v)} | {src if src != last else '″'} |")
            last = src
        L.append("")
    return "\n".join(L)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    out = ROOT / "docs" / "dev" / "PARAMETERS.md"
    text = page()
    if "--check" in argv:
        ok = out.is_file() and out.read_text(encoding="utf-8") == text
        print(
            "docs/dev/PARAMETERS.md is up to date"
            if ok
            else "docs/dev/PARAMETERS.md is out of date: run tools/gen_parameters_md.py"
        )
        return 0 if ok else 1
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
